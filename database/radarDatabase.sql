CREATE TABLE usuario (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    perfil VARCHAR(20) NOT NULL DEFAULT 'usuario',
    telefone VARCHAR(30),
    cidade VARCHAR(120),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE evento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    tipo VARCHAR(50),
    instituicao VARCHAR(200),
    publico_alvo TEXT,
    requisitos TEXT,
    nivel VARCHAR(50),
    modalidade VARCHAR(20),

    preco NUMERIC(12,2) CHECK (preco IS NULL OR preco >= 0),

    cidade VARCHAR(120),
    estado VARCHAR(100),

    data_inicio TIMESTAMPTZ,
    data_fim TIMESTAMPTZ,
    prazo_inscricao TIMESTAMPTZ,

    url_inscricao TEXT,

    origem VARCHAR(30),
    fonte_externa VARCHAR(100),
    id_externo VARCHAR(200),
    importado_em TIMESTAMPTZ,

    status_revisao VARCHAR(20) NOT NULL DEFAULT 'pendente',
    contato_sugestao VARCHAR(254),

    id_sugerido_por BIGINT REFERENCES usuario(id_user) ON DELETE SET NULL,
    id_revisor BIGINT REFERENCES usuario(id_user) ON DELETE SET NULL,

    revisado_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE assunto (
    id_assunto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE evento_assunto (
    id_evento BIGINT NOT NULL REFERENCES evento(id_evento) ON DELETE CASCADE,
    id_assunto BIGINT NOT NULL REFERENCES assunto(id_assunto) ON DELETE CASCADE,

    PRIMARY KEY (id_evento, id_assunto)
);

CREATE TABLE curtida (
    id_user BIGINT NOT NULL REFERENCES usuario(id_user) ON DELETE CASCADE,
    id_evento BIGINT NOT NULL REFERENCES evento(id_evento) ON DELETE CASCADE,

    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (id_user, id_evento)
);

CREATE TABLE comentario (
    id_comentario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_user BIGINT NOT NULL REFERENCES usuario(id_user) ON DELETE CASCADE,
    id_evento BIGINT NOT NULL REFERENCES evento(id_evento) ON DELETE CASCADE,

    texto TEXT NOT NULL,

    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE favorito (
    id_user BIGINT NOT NULL REFERENCES usuario(id_user) ON DELETE CASCADE,
    id_evento BIGINT NOT NULL REFERENCES evento(id_evento) ON DELETE CASCADE,

    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (id_user, id_evento)
);


